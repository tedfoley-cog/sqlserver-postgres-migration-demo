-- H2-compatible schema for Vehicle Operations demo
-- Mirrors the SQL Server schema but uses H2/ANSI SQL syntax

CREATE TABLE IF NOT EXISTS VEHICLE (
    VEHICLEID           INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    VIN                 VARCHAR(17) NOT NULL UNIQUE,
    MODELYEAR           INT NOT NULL,
    MODELCODE           VARCHAR(10) NOT NULL,
    MODELNAME           VARCHAR(50) NOT NULL,
    TRIMLEVEL           VARCHAR(20),
    ENGINECODE          VARCHAR(15),
    TRANSMISSIONTYPE    VARCHAR(10),
    PLANTCODE           VARCHAR(5) NOT NULL,
    ASSEMBLYDATE        TIMESTAMP,
    SHIPDATE            TIMESTAMP,
    DEALERCODE          VARCHAR(10),
    CURRENTMILEAGE      INT DEFAULT 0,
    WARRANTYSTARTDATE   TIMESTAMP,
    WARRANTYENDDATE     TIMESTAMP,
    STATUS              VARCHAR(20) DEFAULT 'IN_PRODUCTION',
    CREATEDDATE         TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    MODIFIEDDATE        TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS PRODUCTIONSTATION (
    STATIONID           INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    STATIONCODE         VARCHAR(15) NOT NULL,
    STATIONNAME         VARCHAR(50) NOT NULL,
    PLANTCODE           VARCHAR(5) NOT NULL,
    SEQUENCEORDER       INT NOT NULL,
    CYCLETIMEMINUTES    DECIMAL(8,2),
    ISQUALITYGATE       BOOLEAN DEFAULT FALSE
);

CREATE TABLE IF NOT EXISTS PRODUCTIONTRACKING (
    TRACKINGID          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    VEHICLEID           INT NOT NULL,
    STATIONID           INT NOT NULL,
    ENTRYTIME           TIMESTAMP NOT NULL,
    EXITTIME            TIMESTAMP,
    OPERATORID          VARCHAR(20),
    STATUS              VARCHAR(20) DEFAULT 'IN_STATION',
    DEFECTSFOUND        INT DEFAULT 0,
    NOTES               VARCHAR(500),
    FOREIGN KEY (VEHICLEID) REFERENCES VEHICLE(VEHICLEID),
    FOREIGN KEY (STATIONID) REFERENCES PRODUCTIONSTATION(STATIONID)
);

CREATE TABLE IF NOT EXISTS WARRANTYCLAIM (
    CLAIMID             INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CLAIMNUMBER         VARCHAR(20) NOT NULL UNIQUE,
    VEHICLEID           INT NOT NULL,
    DEALERCODE          VARCHAR(10) NOT NULL,
    CLAIMDATE           TIMESTAMP NOT NULL,
    MILEAGEATCLAIM      INT NOT NULL,
    SYMPTOMCODE         VARCHAR(10),
    CAUSALPARTNUMBER    VARCHAR(25),
    LABOROPERATIONCODE  VARCHAR(15),
    LABORHOURS          DECIMAL(6,2),
    LABORRATE           DECIMAL(8,2),
    PARTSCOST           DECIMAL(10,2),
    SUBLETCOST          DECIMAL(10,2) DEFAULT 0,
    DEDUCTIBLE          DECIMAL(8,2) DEFAULT 0,
    TOTALAMOUNT         DECIMAL(10,2),
    COVERAGETYPE        VARCHAR(20),
    CLAIMSTATUS         VARCHAR(15) DEFAULT 'SUBMITTED',
    DENIALREASONCODE    VARCHAR(10),
    APPROVEDDATE        TIMESTAMP,
    SETTLEDDATE         TIMESTAMP,
    SUBMITTEDBY         VARCHAR(50),
    CREATEDDATE         TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (VEHICLEID) REFERENCES VEHICLE(VEHICLEID)
);

CREATE TABLE IF NOT EXISTS WARRANTYCOVERAGE (
    COVERAGEID          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    COVERAGETYPE        VARCHAR(20) NOT NULL,
    MODELYEAR           INT NOT NULL,
    MONTHSFROMSALE      INT NOT NULL,
    MILEAGELIMIT        INT NOT NULL,
    DESCRIPTION         VARCHAR(100),
    DEDUCTIBLEAMOUNT    DECIMAL(8,2) DEFAULT 0,
    PARTGROUPCODES      VARCHAR(200)
);

CREATE TABLE IF NOT EXISTS LABORRATESCHEDULE (
    RATEID              INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    REGIONCODE          VARCHAR(10) NOT NULL,
    DEALERTIER          VARCHAR(5) NOT NULL,
    LABORTYPE           VARCHAR(20) NOT NULL,
    HOURLYRATE          DECIMAL(8,2) NOT NULL,
    EFFECTIVEDATE       TIMESTAMP NOT NULL,
    EXPIRATIONDATE      TIMESTAMP
);

CREATE TABLE IF NOT EXISTS PART (
    PARTID              INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PARTNUMBER          VARCHAR(25) NOT NULL UNIQUE,
    DESCRIPTION         VARCHAR(100) NOT NULL,
    PARTGROUPCODE       VARCHAR(10),
    UNITCOST            DECIMAL(10,2),
    LISTPRICE           DECIMAL(10,2),
    WEIGHT              DECIMAL(8,3),
    UNITOFMEASURE       VARCHAR(5) DEFAULT 'EA',
    STATUS              VARCHAR(15) DEFAULT 'ACTIVE',
    SUPERSEDEDBYPARTNO  VARCHAR(25),
    SUPPLIERCODE        VARCHAR(20),
    LEADTIMEDAYS        INT,
    MINORDERQTY         INT DEFAULT 1,
    CREATEDDATE         TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS PARTFITMENT (
    FITMENTID           INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PARTNUMBER          VARCHAR(25) NOT NULL,
    MODELCODE           VARCHAR(10) NOT NULL,
    MODELYEARFROM       INT NOT NULL,
    MODELYEARTO         INT NOT NULL,
    TRIMLEVEL           VARCHAR(20),
    ENGINECODE          VARCHAR(15),
    NOTES               VARCHAR(200)
);

CREATE TABLE IF NOT EXISTS PARTINVENTORY (
    INVENTORYID         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PARTNUMBER          VARCHAR(25) NOT NULL,
    WAREHOUSECODE       VARCHAR(10) NOT NULL,
    ONHANDQTY           INT DEFAULT 0,
    REORDERPOINT        INT DEFAULT 0,
    LASTCOUNTDATE       TIMESTAMP
);

CREATE TABLE IF NOT EXISTS SUPPLIER (
    SUPPLIERID          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    SUPPLIERCODE        VARCHAR(20) NOT NULL UNIQUE,
    SUPPLIERNAME        VARCHAR(100) NOT NULL,
    CONTACTNAME         VARCHAR(50),
    REGION              VARCHAR(10),
    COUNTRY             VARCHAR(30),
    QUALITYRATING       VARCHAR(5),
    ISAPPROVED          BOOLEAN DEFAULT TRUE,
    CERTIFICATIONEXPIRY TIMESTAMP,
    ANNUALVOLUME        INT,
    ONTIMEDELIVERY_PCT  DECIMAL(5,2),
    DEFECTPPM           INT,
    CREATEDDATE         TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS SUPPLIERSHIPMENT (
    SHIPMENTID          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    SUPPLIERCODE        VARCHAR(20) NOT NULL,
    PURCHASEORDERNO     VARCHAR(20),
    PARTNUMBER          VARCHAR(25) NOT NULL,
    SHIPDATE            TIMESTAMP NOT NULL,
    RECEIVEDDATE        TIMESTAMP,
    ORDEREDQTY          INT NOT NULL,
    RECEIVEDQTY         INT,
    REJECTEDQTY         INT DEFAULT 0,
    DUEDATE             TIMESTAMP NOT NULL,
    ISONTIME            BOOLEAN,
    INSPECTIONRESULT    VARCHAR(15)
);

CREATE TABLE IF NOT EXISTS DEALERSETTLEMENT (
    SETTLEMENTID        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    SETTLEMENTBATCHNO   VARCHAR(20) NOT NULL,
    DEALERCODE          VARCHAR(10) NOT NULL,
    CLAIMID             INT,
    LABORAMOUNT         DECIMAL(10,2),
    PARTSAMOUNT         DECIMAL(10,2),
    PARTSMARKUP         DECIMAL(10,2),
    SUBLETAMOUNT        DECIMAL(10,2),
    DEDUCTIBLECREDIT    DECIMAL(8,2) DEFAULT 0,
    NETAMOUNT           DECIMAL(10,2),
    SETTLEMENTDATE      TIMESTAMP,
    PAYMENTSTATUS       VARCHAR(15) DEFAULT 'PENDING',
    FOREIGN KEY (CLAIMID) REFERENCES WARRANTYCLAIM(CLAIMID)
);
